//! Loading compiled variants and the buffers passed to them.

use std::alloc::{alloc_zeroed, dealloc, Layout};
use std::path::Path;
use std::ptr::NonNull;

use anyhow::{Context, Result};
use libloading::Library;

use crate::codegen::SYMBOL;

/// Alignment of every buffer handed to a variant.
pub const ALIGNMENT: usize = 64;

/// A zero-initialized heap buffer aligned to [`ALIGNMENT`] bytes.
pub struct AlignedBuf {
    ptr: NonNull<u8>,
    len: usize,
    layout: Layout,
}

impl AlignedBuf {
    /// A zeroed buffer of `len` bytes.
    pub fn zeroed(len: usize) -> Self {
        let layout = Layout::from_size_align(len.max(ALIGNMENT), ALIGNMENT).expect("valid layout");
        // SAFETY: the layout has a nonzero size.
        let raw = unsafe { alloc_zeroed(layout) };
        let ptr = NonNull::new(raw).unwrap_or_else(|| std::alloc::handle_alloc_error(layout));
        AlignedBuf { ptr, len, layout }
    }

    /// Length in bytes.
    pub fn len(&self) -> usize {
        self.len
    }

    /// Whether the buffer is empty.
    pub fn is_empty(&self) -> bool {
        self.len == 0
    }

    /// The bytes.
    pub fn as_slice(&self) -> &[u8] {
        // SAFETY: `ptr` is valid for `len` initialized bytes.
        unsafe { std::slice::from_raw_parts(self.ptr.as_ptr(), self.len) }
    }

    /// The bytes, mutably.
    pub fn as_mut_slice(&mut self) -> &mut [u8] {
        // SAFETY: `ptr` is valid for `len` initialized bytes and uniquely borrowed.
        unsafe { std::slice::from_raw_parts_mut(self.ptr.as_ptr(), self.len) }
    }

    /// Raw pointer to the first byte.
    pub fn as_ptr(&self) -> *const u8 {
        self.ptr.as_ptr()
    }

    /// Raw mutable pointer to the first byte.
    pub fn as_mut_ptr(&mut self) -> *mut u8 {
        self.ptr.as_ptr()
    }
}

impl Drop for AlignedBuf {
    fn drop(&mut self) {
        // SAFETY: allocated in `zeroed` with this layout.
        unsafe { dealloc(self.ptr.as_ptr(), self.layout) }
    }
}

/// The exported batch function.
pub type MixBatch = unsafe extern "C" fn(*const u8, *mut u8, usize);

/// A loaded variant library.
pub struct Variant {
    pub id: String,
    func: MixBatch,
    /// Keeps the library mapped while `func` is in use.
    _lib: Library,
}

impl Variant {
    /// Loads the library at `path` and resolves [`SYMBOL`].
    pub fn load(id: &str, path: &Path) -> Result<Self> {
        // SAFETY: the library was generated by this crate from a validated
        // program; its initializers are the Rust standard library's.
        let lib =
            unsafe { Library::new(path) }.with_context(|| format!("loading {}", path.display()))?;
        // SAFETY: the generated crate exports `mix_batch` with this signature.
        let func: MixBatch = unsafe {
            *lib.get::<MixBatch>(SYMBOL.as_bytes())
                .with_context(|| format!("resolving {SYMBOL} in {}", path.display()))?
        };
        Ok(Variant {
            id: id.to_string(),
            func,
            _lib: lib,
        })
    }

    /// Calls `mix_batch` on `columns` columns of `column_bytes` bytes each,
    /// starting `offset` columns into both buffers.
    ///
    /// # Panics
    ///
    /// If either buffer is too short, or the two buffers are the same.
    pub fn call_at(
        &self,
        input: &AlignedBuf,
        output: &mut AlignedBuf,
        column_bytes: usize,
        offset: usize,
        columns: usize,
    ) {
        let start = offset * column_bytes;
        let end = (offset + columns) * column_bytes;
        assert!(
            end <= input.len() && end <= output.len(),
            "buffer too short"
        );
        // SAFETY: both ranges lie inside their (distinct, non-overlapping)
        // allocations, which are aligned for every column word.
        unsafe {
            (self.func)(
                input.as_ptr().add(start),
                output.as_mut_ptr().add(start),
                columns,
            )
        }
    }

    /// Calls `mix_batch` on the first `columns` columns of both buffers.
    #[inline]
    pub fn call(
        &self,
        input: &AlignedBuf,
        output: &mut AlignedBuf,
        column_bytes: usize,
        columns: usize,
    ) {
        self.call_at(input, output, column_bytes, 0, columns)
    }

    /// The raw function, for timing loops that check bounds once outside.
    pub fn raw(&self) -> MixBatch {
        self.func
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn buffers_are_aligned_and_zeroed() {
        for len in [0, 1, 63, 64, 4096, 1 << 20] {
            let b = AlignedBuf::zeroed(len);
            assert_eq!(b.as_ptr() as usize % ALIGNMENT, 0);
            assert_eq!(b.len(), len);
            assert!(b.as_slice().iter().all(|&x| x == 0));
        }
    }
}
